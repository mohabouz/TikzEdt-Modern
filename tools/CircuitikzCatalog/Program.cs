using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

// Reads documented component declarations, never executes the downloaded TeX.
// Usage: dotnet run --project tools/CircuitikzCatalog -- <output.json> [manual.tex]
if (args.Length == 0) throw new ArgumentException("Specify the output catalogue JSON path.");
const string sourceUrl = "https://raw.githubusercontent.com/circuitikz/circuitikz/master/doc/circuitikzmanual.tex";
using var http = new HttpClient { Timeout = TimeSpan.FromSeconds(45) };
http.DefaultRequestHeaders.UserAgent.ParseAdd("TikzEdt-Catalogue-Generator/1.0");
var manual = args.Length > 1 ? await File.ReadAllTextAsync(args[1]) : await http.GetStringAsync(sourceUrl);
var sourceHash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(manual)));
var start = manual.IndexOf(@"\section{The components: list}", StringComparison.Ordinal);
if (start < 0) throw new InvalidDataException("Cannot find the manual's full component list.");
var end = manual.IndexOf(@"\section{", start + 10, StringComparison.Ordinal);
var catalogue = manual[start..(end < 0 ? manual.Length : end)];
catalogue = Regex.Replace(catalogue, @"(?m)(?<!\\)%[^\r\n]*", "");
var entries = new Dictionary<string, Entry>(StringComparer.Ordinal);
var category = "Components";
var declarations = 0;
foreach (Match match in Regex.Matches(catalogue, @"\\(?<kind>subsection|circuitdescbip|circuitdesc)(?![a-zA-Z])"))
{
    var offset = match.Index + match.Length;
    var kind = match.Groups["kind"].Value;
    SkipWhite(catalogue, ref offset);
    if (offset < catalogue.Length && catalogue[offset] == '*') offset++;
    SkipWhite(catalogue, ref offset);
    string? optional = null;
    if (offset < catalogue.Length && catalogue[offset] == '[') optional = ReadGroup(catalogue, ref offset, '[', ']');
    var key = ReadGroup(catalogue, ref offset, '{', '}');
    if (kind == "subsection") { category = Plain(key); continue; }
    declarations++;
    SkipWhite(catalogue, ref offset);
    string? nodeName = null;
    if (offset < catalogue.Length && catalogue[offset] == '<') nodeName = ReadGroup(catalogue, ref offset, '<', '>');
    var description = ReadGroup(catalogue, ref offset, '{', '}');
    var aliasesOrText = ReadGroup(catalogue, ref offset, '{', '}');
    if (key.Contains('\\') || key.Contains('#')) throw new InvalidDataException("Unhandled component template: " + key);
    if (kind == "circuitdescbip")
    {
        Add(key, "Path", category, "", key);
        foreach (var alias in aliasesOrText.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries))
            if (!alias.Contains('\\') && !alias.Contains('#')) Add(alias, "Path", category, "", key);
        var shape = nodeName ?? (optional ?? key) + "shape";
        Add(shape, "Node", category, "", key);
    }
    else
        Add(key, "Node", category, aliasesOrText, key);
}
// These connection poles are documented separately in section 6.1, rather
// than through the catalogue's circuitdesc macros.
foreach (var pole in new[] { "circ", "ocirc", "squarepole", "osquarepole", "diamondpole", "odiamondpole", "rectfill" })
    Add(pole, "Node", "Connection poles", "", pole);
var polesStart = manual.IndexOf(@"\subsection{Nodes (also called poles)}", StringComparison.Ordinal);
if (polesStart >= 0)
{
    var polesEnd = manual.IndexOf(@"\subsection{Mirroring", polesStart, StringComparison.Ordinal);
    var polesText = manual[polesStart..(polesEnd < 0 ? manual.Length : polesEnd)];
    foreach (Match poleStyle in Regex.Matches(polesText, @"to\[R,\s*([*od\-]+)\]"))
        Add("R, " + poleStyle.Groups[1].Value, "Path", "Connection poles", "", "bipole nodes");
}
Add("seven segment val=8 dot on box on", "Node", "Seven segment displays", "", "bare7seg");
foreach (var name in new[] { "D", "sD", "zD", "zzD", "tD", "pD", "leD", "VC", "Ty", "Tr" })
    Add(name, "Path", "Diodes and such", "", name);
Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(args[0]))!);
var output = new
{
    Source = sourceUrl,
    ManualSha256 = sourceHash,
    GeneratedUtc = DateTimeOffset.UtcNow,
    ManualDeclarations = declarations,
    Notice = "Component identifiers extracted from the official CircuiTikZ manual. Examples are generated by TikzEdt. See CircuitikzCatalog.README.md for attribution and coverage.",
    Entries = entries.Values.OrderBy(entry => entry.Category).ThenBy(entry => entry.Name).ToArray()
};
await File.WriteAllTextAsync(args[0], JsonSerializer.Serialize(output, new JsonSerializerOptions { WriteIndented = true }));
Console.WriteLine($"Read {declarations} manual declarations; generated {entries.Count} path, node, and alias snippets. SHA256: {sourceHash}");

void Add(string key, string type, string group, string nodeText, string canonical)
{
    if (string.IsNullOrWhiteSpace(key) || key.Contains('\\') || key.Contains('#')) return;
    var identity = type + ":" + key;
    var code = type == "Path" ? $"\\draw (0,0) to[{key}] (3,0);" : $"\\node[{key}] at (0,0) {{{nodeText}}};";
    entries.TryAdd(identity, new Entry("circuitikz:" + identity, key + (type == "Node" ? " (node)" : ""),
        "Circuitikz / " + group, $"{type}-style element: {key}." + (canonical != key ? $" Related element: {canonical}." : ""),
        "% !TIKZEDT PACKAGE circuitikz\n" + code,
        "% !TIKZEDT PACKAGE circuitikz\n\\begin{tikzpicture}\n" + code + "\n\\end{tikzpicture}", "circuitikz"));
}

static void SkipWhite(string value, ref int offset) { while (offset < value.Length && char.IsWhiteSpace(value[offset])) offset++; }
static string ReadGroup(string value, ref int offset, char opening, char closing)
{
    SkipWhite(value, ref offset);
    if (offset >= value.Length || value[offset] != opening)
        throw new InvalidDataException($"Expected '{opening}' near: {value.Substring(Math.Max(0, offset - 25), Math.Min(100, value.Length - Math.Max(0, offset - 25)))}");
    var start = ++offset;
    var depth = 1;
    while (offset < value.Length)
    {
        var character = value[offset++];
        if (character == '\\') { if (offset < value.Length && "{}%[]".Contains(value[offset])) offset++; continue; }
        if (character == opening) depth++;
        else if (character == closing && --depth == 0) return value[start..(offset - 1)].Trim();
    }
    throw new InvalidDataException("Unclosed manual argument.");
}
static string Plain(string value) => Regex.Replace(Regex.Replace(value, @"\\[a-zA-Z]+\*?", ""), @"[{}]", "").Trim();
internal sealed record Entry(string Id, string Name, string Category, string Description, string Code, string Sample, string RequiredPackages);
